def _dataset_overview(db: Session, crime_type: str | None = None, date_from=None, date_to=None, top_n: int = 8) -> dict:
    """
    Dataset-wide descriptive snapshot — no ML, no forecasting — for questions
    that ask about the current data as a whole rather than one district/ward
    (e.g. "which districts have the most incidents", "what crime types are
    most common"). generate_intelligence_brief() cannot answer these: it is
    built around a single district/ward drilldown and returns
    "selection_required" without one. This is a straightforward COUNT/GROUP
    BY over the same Incident table every other module already queries.
    """
    q = db.query(Incident)
    if crime_type: q = q.filter(Incident.crime_type == crime_type)
    if date_from: q = q.filter(Incident.timestamp >= date_from)
    if date_to: q = q.filter(Incident.timestamp <= date_to)
    total = q.count()
    if total == 0:
        return {"status": "no_data", "total_incidents": 0}
    by_district = (q.with_entities(Incident.district, func.count(Incident.id))
                    .group_by(Incident.district).order_by(func.count(Incident.id).desc()).limit(top_n).all())
    by_crime_type = (q.with_entities(Incident.crime_type, func.count(Incident.id))
                       .group_by(Incident.crime_type).order_by(func.count(Incident.id).desc()).limit(top_n).all())
    date_bounds = q.with_entities(func.min(Incident.timestamp), func.max(Incident.timestamp)).first()
    return {
        "status": "ok",
        "total_incidents": total,
        "districts_by_incident_count": [{"district": d, "count": n} for d, n in by_district],
        "crime_types_by_count": [{"crime_type": c, "count": n} for c, n in by_crime_type],
        "date_range": {
            "from": date_bounds[0].isoformat() if date_bounds and date_bounds[0] else None,
            "to": date_bounds[1].isoformat() if date_bounds and date_bounds[1] else None,
        },
    }


def _summarize_risk(risk: dict, top_n: int = 15) -> dict:
    """
    predict_risk() returns one row per ward in scope — for a dataset-wide or
    district-wide (no single ward) request that can be 100+ rows, each
    carrying a verbose SHAP explanation. _compact()'s generic size-based
    truncation has no notion of "predictions" and would silently drop the
    entire list once the serialized evidence crosses its size limit, making
    a genuinely available forecast look like "no data" downstream. Trim to
    the top-N highest-risk wards with only the essential fields (dropping
    per-ward SHAP factor breakdowns, which the dashboard's own risk view
    already renders) so the real forecast signal survives compaction.
    """
    preds = risk.get("predictions") or []
    if len(preds) <= top_n:
        return risk
    valid = sorted((p for p in preds if not p.get("insufficient_data")), key=lambda p: p.get("risk_score") or 0, reverse=True)
    kept_source = valid if valid else preds
    kept = [
        {k: p.get(k) for k in ("ward_id", "ward_name", "district", "prediction_horizon_days",
                                "insufficient_data", "risk_score", "risk_level", "predicted_incidents",
                                "confidence", "trend")}
        for p in kept_source[:top_n]
    ]
    return {**risk, "predictions": kept,
            "predictions_summary": {"total_wards": len(preds), "wards_with_valid_forecast": len(valid), "shown": len(kept)}}


def _summarize_hotspots(hotspots: dict, top_n: int = 10) -> dict:
    """
    detect_hotspots() returns every clustered incident coordinate: a global
    scope serializes to ~590KB (a 2400-entry `points` list, plus a per-cluster
    `points` list inside each of ~91 clusters). That is ~65x _compact()'s size
    limit, and _compact()'s generic truncation has no notion of "n_clusters",
    so it discarded every count and left only `params` — which is why the
    Copilot reported "0 clusters from 0 incidents" while the Hotspots
    dashboard, reading the same detect_hotspots() output straight from
    /api/hotspots, correctly showed 91 clusters from 2400 incidents.

    Keep the headline counts and the top-N clusters by risk score, dropping
    only the raw coordinate lists (the map renders those from /api/hotspots
    itself; they carry no analytical meaning for a text answer).
    """
    clusters = hotspots.get("clusters") or []
    ranked = sorted(clusters, key=lambda c: c.get("risk_score") or 0, reverse=True)
    return {
        "params": hotspots.get("params"),
        "auto_tuned": hotspots.get("auto_tuned"),
        "n_incidents": hotspots.get("n_incidents", 0),
        "n_clusters": hotspots.get("n_clusters", 0),
        "n_noise": hotspots.get("n_noise", 0),
        "severity_breakdown": {
            level: sum(1 for c in clusters if c.get("severity_level") == level)
            for level in ("High", "Medium", "Low")
        },
        "districts_by_hotspot_count": [
            {"district": d, "hotspots": n, "max_risk_score": m}
            for d, n, m in sorted(
                ((d, sum(1 for c in clusters if c.get("district") == d),
                  max((c.get("risk_score") or 0) for c in clusters if c.get("district") == d))
                 for d in {c.get("district") for c in clusters if c.get("district")}),
                key=lambda row: (row[2], row[1]), reverse=True)[:top_n]
        ],
        "top_clusters": [
            {k: c.get(k) for k in ("cluster_id", "district", "ward_id", "risk_score", "severity_level",
                                    "incident_count", "dominant_crime_type", "avg_severity", "radius_m", "centroid")}
            for c in ranked[:top_n]
        ],
        "clusters_shown": min(len(ranked), top_n),
    }


def _compact(data: Any, limit: int = 9000):
    if not data:
        return None
    serialized = json.dumps(data, default=str, allow_nan=False)
    if len(serialized) <= limit:
        return json.loads(serialized)
    if isinstance(data, dict):
        compact = {k: data[k] for k in ("status", "summary", "params", "scope", "priority", "headline", "key_development", "predictive_risk", "alerts", "hotspots", "network", "why_it_matters", "analytical_followups", "predictions", "predictions_summary", "model_performance", "n_incidents", "n_clusters", "n_noise", "severity_breakdown", "districts_by_hotspot_count", "top_clusters", "clusters_shown") if k in data}
        return json.loads(json.dumps(compact, default=str, allow_nan=False))
    return {"truncated": True, "summary": f"{len(data)} records available; only a compact analytical summary was supplied."}


def build_evidence_context(db: Session, message: str, context: dict) -> dict:
    intent = route_intent(message)
    district, ward_id, crime = _scope(db, message, context)
    date_from, date_to = _dates(context)
    horizon = int(context.get("prediction_horizon") or context.get("horizonDays") or 14)
    granularity = context.get("granularity") or context.get("trendGranularity") or "weekly"
    base = {"intent": intent, "scope": {"district": district, "ward_id": ward_id, "crime_type": crime}, "sources": []}

    if intent == "UNAVAILABLE_DATA":
        base.update({"sources": []})
        return base
    if intent in ("SUMMARY", "FOLLOW_UP", "GENERAL_ANALYTICS"):
        if district or ward_id is not None:
            brief = _brief_context(db, district, ward_id, crime, date_from, date_to, horizon, granularity)
            base.update({"brief": _compact(brief), "sources": ["Intelligence Brief"]})
        else:
            base.update({"overview": _dataset_overview(db, crime_type=crime, date_from=date_from, date_to=date_to), "sources": ["Dataset Overview"]})
        return base
    if intent == "OUT_OF_SCOPE":
        base.update({"sources": []})
        return base
    if intent == "RISK":
        risk = predict_risk(db, district=district, ward_id=ward_id, crime_type=crime, horizon_days=horizon, as_of=date_to)
        base.update({"risk": _compact(_summarize_risk(risk)), "sources": ["Predictive Risk"]})
        # Forecast evidence alone can't answer "what's happening now" — attach
        # the same current-data context SUMMARY uses, so a RISK-intent question
        # can still be answered descriptively when the forecast is unreliable.
        if district or ward_id is not None:
            base["brief"] = _compact(_brief_context(db, district, ward_id, crime, date_from, date_to, horizon, granularity))
            base["sources"].append("Intelligence Brief")
        else:
            base["overview"] = _dataset_overview(db, crime_type=crime, date_from=date_from, date_to=date_to)
            base["sources"].append("Dataset Overview")
        return base
    if intent == "TREND":
        trend = analyze_trends(db, district=district, ward_id=ward_id, crime_type=crime, date_from=date_from, date_to=date_to, granularity=granularity)
        base.update({"trend": _compact(trend), "sources": ["Trend Analytics"]})
        return base
    if intent == "ALERT":
        alerts = generate_alerts(db, district=district, ward_id=ward_id, crime_type=crime, date_from=date_from, date_to=date_to, granularity=granularity)
        base.update({"alerts": _compact(alerts), "sources": ["Intelligence Alerts"]})
        return base
    if intent == "HOTSPOT":
        hotspots = detect_hotspots(db, district=district, crime_type=crime, date_from=date_from, date_to=date_to)
        logger.info(
            "copilot hotspot query: district=%s crime_type=%s date_from=%s date_to=%s -> n_incidents=%s n_clusters=%s",
            district, crime, date_from, date_to, hotspots.get("n_incidents"), hotspots.get("n_clusters"),
        )
        base.update({"hotspots": _compact(_summarize_hotspots(hotspots)), "sources": ["Hotspot Analytics"]})
        return base
    if intent in ("NETWORK", "OFFENDER"):
        network = build_network(db, ward_id=ward_id, district=district, crime_type=crime, date_from=date_from, date_to=date_to)
        if intent == "OFFENDER":
            network = {"summary": network.get("summary"), "nodes": [n for n in network.get("nodes", []) if n.get("incident_count", 0) > 1][:8]}
        base.update({"network": _compact(network), "sources": ["Network Analytics", "Repeat Offender Analytics"]})
        return base
    if intent == "INCIDENT":
        # Pre-existing bug: .limit() must come after .filter() — SQLAlchemy
        # rejects filtering a query that already has LIMIT/OFFSET applied,
        # so any district/ward/crime-scoped "recent incidents" question
        # (e.g. from AI Mitra with a district selected) raised
        # InvalidRequestError and surfaced as a raw 500 from /api/copilot.
        q = db.query(Incident)
        if district: q = q.filter(Incident.district == district)
        if ward_id is not None: q = q.filter(Incident.ward_id == ward_id)
        if crime: q = q.filter(Incident.crime_type == crime)
        q = q.order_by(Incident.timestamp.desc()).limit(5)
        incidents = [{"id": i.id, "timestamp": i.timestamp.isoformat(), "crime_type": i.crime_type, "severity": i.severity, "district": i.district, "ward_id": i.ward_id} for i in q.all()]
        base.update({"incidents": incidents, "sources": ["Incident Records"]})
        return base
    return base


def _find_compare_wards(db: Session, message: str, district: str | None) -> list[Ward]:
    wards = db.query(Ward).filter(Ward.district == district).all() if district else db.query(Ward).all()
    q = message.lower()
    matches = [w for w in wards if w.name.lower() in q]
    return matches[:2] if len(matches) >= 2 else []


