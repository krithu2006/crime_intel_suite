# Explicit hotspot nouns (deliberately excluding the very generic "where",
# which stays in the later, lower-priority HOTSPOT check) and the forecast
# verbs that let a genuine prediction question outrank them. See route_intent.
_HOTSPOT_NOUNS = ("hotspot", "hot spot", "cluster", "ಹಾಟ್‌ಸ್ಪಾಟ್", "ಹಾಟ್ ಸ್ಪಾಟ್", "हॉटस्पॉट")
_FORECAST_VERBS = ("predict", "forecast", "ಮುನ್ಸೂಚನೆ", "पूर्वानुमान")


def _localized_level(value: Any, lang: str) -> str:
    """Translate dashboard status words that otherwise leak into AI output."""
    value = str(value or "").lower()
    labels = {
        "kn": {"critical": "ಗಂಭೀರ", "high": "ಹೆಚ್ಚಿನ", "medium": "ಮಧ್ಯಮ", "low": "ಕಡಿಮೆ", "rising": "ಹೆಚ್ಚುತ್ತಿದೆ", "falling": "ಕಡಿಮೆಯಾಗುತ್ತಿದೆ", "stable": "ಸ್ಥಿರ"},
        "hi": {"critical": "गंभीर", "high": "उच्च", "medium": "मध्यम", "low": "निम्न", "rising": "बढ़ता हुआ", "falling": "घटता हुआ", "stable": "स्थिर"},
    }
    return labels.get(lang, {}).get(value, value.upper())


def route_intent(message: str) -> str:
    """
    Ordered, mutually-exclusive keyword routing. Order matters: earlier
    branches win. Two failure modes drove this ordering —
      1. "attention"/"priority" used to sit in the RISK keyword list, so any
         analytical question phrased as "what should an investigator pay
         attention to" was misrouted into forecast-only evidence and got the
         RISK branch's insufficient-data text, however good the historical
         data actually was for a *descriptive* answer.
      2. A bare "why"/"next" catch-all used to run BEFORE the domain-specific
         checks and defaulted to RISK, so e.g. "...anomalies... explain why
         each one is important" (a TREND question) was misrouted to RISK too.
    Domain-specific checks now all run before that catch-all, RISK no longer
    fires on generic analytical language, and the catch-all's result is
    FOLLOW_UP (general-analytics evidence), never RISK — RISK is reserved for
    genuine forecast/prediction language.
    """
    q = message.lower()
    if any(x in q for x in ("cricket", "football", "weather", "stock price", "recipe", "movie review")): return "OUT_OF_SCOPE"
    if any(x in q for x in UNAVAILABLE_DATA_TOPICS): return "UNAVAILABLE_DATA"
    # A hotspot noun outranks the generic "compare"/"risk" keywords below:
    # - "Compare the top 5 hotspots" matched COMPARE first, which only knows
    #   how to compare two named WARDS by text-matching; finding none, it
    #   dead-ended with "I could not reliably identify two wards to compare"
    #   instead of ranking hotspots (which the HOTSPOT evidence already
    #   contains, pre-sorted by risk, and the LLM prompt already knows to
    #   render a comparison of several ranked items as a table).
    # - "which hotspot has the highest RISK score" / "highest-RISK hotspots"
    #   are questions about DBSCAN cluster risk scores (descriptive, from
    #   detect_hotspots), not the ward-level predictive forecast; they used
    #   to match the RISK branch below and come back with forecast evidence
    #   and no hotspot data at all.
    # Explicit forecast verbs still win, so "predict future hotspots" still
    # routes to the predictive model, and a ward-to-ward comparison with no
    # hotspot noun ("compare Ward A and Ward B") is untouched.
    if any(x in q for x in _HOTSPOT_NOUNS) and not any(x in q for x in _FORECAST_VERBS): return "HOTSPOT"
    if any(x in q for x in ("compare", "versus", " vs ", "difference between")): return "COMPARE"
    if "which ward" in q and any(x in q for x in ("attention", "priority", "focus")): return "SUMMARY"
    if any(x in q for x in ("risk", "predict", "forecast", "future", "high risk", "ಅಪಾಯ", "ಮುನ್ಸೂಚನೆ", "जोखिम", "पूर्वानुमान")): return "RISK"
    if any(x in q for x in ("trend", "changed", "change", "rising", "increasing", "baseline", "anomal", "ಪ್ರವೃತ್ತ", "ಬದಲಾವಣೆ", "ट्रेंड", "परिवर्तन", "बढ़")): return "TREND"
    if any(x in q for x in ("alert", "warning", "ಎಚ್ಚರ", "अलर्ट", "चेतावनी")): return "ALERT"
    if any(x in q for x in ("hotspot", "cluster", "where", "ಹಾಟ್‌ಸ್ಪಾಟ್", "ಹಾಟ್ ಸ್ಪಾಟ್", "हॉटस्पॉट")): return "HOTSPOT"
    if any(x in q for x in ("network", "connected", "connector", "community", "linked", "ಜಾಲ", "नेटवर्क", "जुड़")): return "NETWORK"
    if any(x in q for x in ("offender", "accused", "repeat", "ಅಪರಾಧಿ", "ಆರೋಪಿ", "अपराधी", "आरोपी")): return "OFFENDER"
    if any(x in q for x in ("summar", "important", "intelligence picture", "what's here", "what is here")): return "SUMMARY"
    # "incident(s)" alone is too generic to mean "show raw recent records" —
    # it appears in almost any crime question. Only route to a raw incident
    # dump for language that specifically asks for recent/latest activity.
    if any(x in q for x in ("happened", "recent incident", "latest incident", "recent activity", "ಘಟನೆ", "घटना")): return "INCIDENT"
    if any(x in q for x in ("why", "what should i inspect", "next", "follow-up")) and "alert" not in q and "risk" not in q:
        return "FOLLOW_UP"
    return "GENERAL_ANALYTICS"


def _dates(context: dict) -> tuple[datetime | None, datetime | None]:
    def parse(value, end_of_day=False):
        try:
            parsed = datetime.fromisoformat(value) if value else None
            if parsed and end_of_day and "T" not in value and " " not in value:
                return datetime.combine(parsed.date(), time.max)
            return parsed
        except (TypeError, ValueError): return None
    return parse(context.get("date_from")), parse(context.get("date_to"), end_of_day=True)


def _extract_district_from_text(db: Session, message: str) -> str | None:
    """
    Best-effort scope detection from free text — e.g. "Analyze Kalaburagi
    district" should be Kalaburagi-scoped even when the dashboard's district
    filter isn't set, matching against real district names rather than
    guessing or inventing one.
    """
    q = message.lower()
    for (name,) in db.query(Ward.district).distinct().all():
        if name and name.lower() in q:
            return name
    return None


def _scope(db: Session, message: str, context: dict) -> tuple[str | None, int | None, str | None]:
    district = context.get("district") or context.get("selectedDistrict")
    ward_id = context.get("ward_id")
    if ward_id is None and isinstance(context.get("selectedWard"), dict): ward_id = context["selectedWard"].get("id")
    crime = context.get("crime_type") or context.get("selectedCrimeType")
    if not district and ward_id is None:
        district = _extract_district_from_text(db, message)
    return district or None, int(ward_id) if ward_id is not None else None, crime or None


